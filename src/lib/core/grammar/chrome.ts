// The workbench half of the two Monaco themes (Brand batch, v1.2.0): every colour Monaco paints
// that is not a token of the NC syntax — the surface, the current line, the selection, the
// gutter, the cursor, the widgets (find, suggest, hover, menus), the minimap and the scrollbars.
//
// They are the values of the tokens in `src/app.css` (peterbuilds' slate surfaces and the one
// orange, #F25C19), spelled out because Monaco takes `#rrggbb` / `#rrggbbaa` strings and cannot
// read a CSS variable. `src/lib/brand/tokens.test.ts` reads both files and fails when one of
// them moves without the other, and holds the pairs that carry text to their contrast ratios.
//
// Orange is used the way the chrome uses it: the cursor, the selection and the find marks
// (things you act on), and the focus ring. Squiggles and the diff tints use the signal colours,
// never the orange.

